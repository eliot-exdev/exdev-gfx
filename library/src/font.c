static void font_init_topaz_8(Font_t *f) {
    assert(f);

    f->width = TOPAZ_8_WIDTH;
    f->height = TOPAZ_8_HEIGHT;
    f->spacing = TOPAZ_8_SPACING;
    f->num_characters = TOPAZ_8_NUM_CHARS;
    f->characters = TOPAZ_8_CHARACTERS[0];
    f->table = TOPAZ_8_TRANSLATION_TABLE;
}

void font_init(Font_t *f, const enum font_type t) {
    assert(f);

    switch (t) {
        case FONT_TYPE_MIA_1:
            font_init_mia_1(f);
            break;
        case FONT_TYPE_TOPAZ_8:
            font_init_topaz_8(f);
            break;
    }
}

void font_deinit(Font_t *font) { (void) (font); }

const char *font_get_character(const Font_t *f, const char c) {
    assert(f);

    for (int i = 0; i < f->num_characters; ++i) {
        if (f->table[i].c == c) {
            return f->characters + f->table[i].pos * f->width * f->height;
        }
    }
    return f->characters;// return first
}
